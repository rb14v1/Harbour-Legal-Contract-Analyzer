"""
Azure OpenAI abstraction: chat completions + embeddings.

Real path: `openai`'s `AzureOpenAI` client, used when AZURE_OPENAI_ENDPOINT +
AZURE_OPENAI_API_KEY are configured.

Stub path: deterministic SHA256-seeded text (chat) / vectors (embeddings),
so demo answers and embeddings are reproducible across runs with zero
network calls and zero cost.
"""
import hashlib
import struct

from django.conf import settings


def _is_real() -> bool:
    return bool(settings.AZURE_OPENAI_ENDPOINT and settings.AZURE_OPENAI_API_KEY)


def _get_client():
    from openai import AzureOpenAI

    return AzureOpenAI(
        azure_endpoint=settings.AZURE_OPENAI_ENDPOINT,
        api_key=settings.AZURE_OPENAI_API_KEY,
        api_version=settings.AZURE_OPENAI_API_VERSION,
    )


def pad_vector(values: list[float], dimensions: int | None = None) -> list[float]:
    """Truncate or zero-pad `values` to exactly `dimensions` floats."""
    dimensions = dimensions or settings.EMBEDDING_DIMENSIONS
    if len(values) >= dimensions:
        return list(values[:dimensions])
    return list(values) + [0.0] * (dimensions - len(values))


def _seeded_floats(seed_text: str, count: int) -> list[float]:
    """Deterministic pseudo-random floats in [-1, 1], SHA256-seeded from seed_text."""
    values = []
    counter = 0
    while len(values) < count:
        digest = hashlib.sha256(f"{seed_text}:{counter}".encode("utf-8")).digest()
        # unpack 8 unsigned 32-bit ints per 32-byte digest
        for chunk in struct.unpack(">8I", digest):
            values.append((chunk / 0xFFFFFFFF) * 2.0 - 1.0)
        counter += 1
    return values[:count]


def generate_embedding(text: str, model: str | None = None) -> list[float]:
    """Return an EMBEDDING_DIMENSIONS-length embedding vector for `text`."""
    model = model or settings.OPENAI_EMBEDDING_MODEL

    if _is_real():
        client = _get_client()
        response = client.embeddings.create(model=model, input=text)
        return pad_vector(response.data[0].embedding, settings.EMBEDDING_DIMENSIONS)

    return pad_vector(_seeded_floats(text, settings.EMBEDDING_DIMENSIONS), settings.EMBEDDING_DIMENSIONS)


def _stub_chat_reply(messages: list[dict]) -> str:
    user_messages = [m["content"] for m in messages if m.get("role") == "user"]
    context = user_messages[-1] if user_messages else ""
    digest = hashlib.sha256(context.encode("utf-8")).hexdigest()[:12]
    snippet = " ".join(context.split())[:280]
    return (
        f"[stub-answer:{digest}] Based on the retrieved contract clauses provided below, "
        f"here is a deterministic demo analysis. Key context considered: \"{snippet}\". "
        "This response was generated by the local deterministic stub because no "
        "AZURE_OPENAI_ENDPOINT/AZURE_OPENAI_API_KEY is configured; in production this "
        f"call would use the '{settings.OPENAI_CHAT_MODEL}' Azure OpenAI chat deployment."
    )


def chat_completion(messages: list[dict], model: str | None = None, temperature: float = 0.2) -> str:
    """
    `messages` is a list of {"role": "system"|"user"|"assistant", "content": str}.
    Returns the assistant's reply text.
    """
    model = model or settings.OPENAI_CHAT_MODEL

    if _is_real():
        client = _get_client()
        response = client.chat.completions.create(
            model=model, messages=messages, temperature=temperature
        )
        return response.choices[0].message.content

    return _stub_chat_reply(messages)


def is_stub_mode() -> bool:
    return not _is_real()
